def check_sub_table():
    """Check if substitution table is a valid permutation"""
    table = get_default_substitution_table()
    print(f"Table length: {len(table)}")
    
    # Check for duplicates
    unique_values = set(table)
    print(f"Number of unique values: {len(unique_values)}")
    print(f"Is permutation (all unique): {len(unique_values) == len(table)}")
    
    # Show some values
    print(f"First 20 values: {list(table[:20])}")
    print(f"Sample: table[0x13]={table[0x13]:02x}, table[0xa6]={table[0xa6]:02x}")
    
    # Find where 0x25 appears in the table
    positions_of_0x25 = []
    for i, val in enumerate(table):
        if val == 0x25:
            positions_of_0x25.append(i)
    print(f"Value 0x25 appears at positions: {positions_of_0x25}")
    
    # Check if table is a proper permutation by ensuring no duplicates
    if len(unique_values) == len(table):
        print("The table is a valid permutation!")
        # Build reverse table properly
        reverse_table = [0] * 256
        for i in range(256):
            reverse_table[table[i]] = i
        print("Reverse table built correctly.")
    else:
        print("The table has duplicates - this is not a valid substitution cipher!")
        # Find duplicates
        seen = set()
        duplicates = set()
        for i, val in enumerate(table):
            if val in seen:
                duplicates.add(val)
            seen.add(val)
        print(f"Duplicates: {[f'0x{d:02x}' for d in duplicates]}")

