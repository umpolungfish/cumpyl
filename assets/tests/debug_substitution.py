def debug_substitution():
    """Debug substitution function"""
    print("Debugging substitution...")
    
    test_data = bytes([0x13, 0x7a, 0x32, 0x32, 0x2a])  # From the debug output above
    print(f"Test data: {test_data.hex()}")
    
    table = get_default_substitution_table()
    print(f"Table length: {len(table)}")
    
    # Apply substitution (forward)
    substituted = bytes(table[b] for b in test_data)
    print(f"After substitution: {substituted.hex()}")
    
    # Build reverse table
    reverse_table = [0] * 256
    for i in range(256):
        reverse_table[table[i]] = i
        
    print(f"Reverse table built. First few entries: {reverse_table[:10]}")
    print(f"Table[0x13]: 0x{table[0x13]:02x}, reverse_table[0x{table[0x13]:02x}]: 0x{reverse_table[table[0x13]]:02x}")
    
    # Apply reverse substitution
    unsubstituted = bytes(reverse_table[b] for b in substituted)
    print(f"After reverse substitution: {unsubstituted.hex()}")
    
    print(f"Match: {test_data == unsubstituted}")
    
    # Test individual values
    print("\nTesting individual values:")
    for b in test_data:
        substituted_val = table[b]
        unsubstituted_val = reverse_table[substituted_val]
        match = (b == unsubstituted_val)
        print(f"0x{b:02x} -> 0x{substituted_val:02x} -> 0x{unsubstituted_val:02x} -> Match: {match}")

if __name__ == "__main__":
    debug_substitution()